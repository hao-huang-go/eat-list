-- Where one checklist ranks among everyone's in the same city and year, on several measures, plus
-- the restaurants where this person is a top-three regular.
create or replace function public.food_stats(p_id uuid) returns json
language sql
stable
set search_path = public
as $$
  with me as (select * from food_checkins where id = p_id),
  peers as (select c.id from food_checkins c, me where c.city = me.city and c.year = me.year),
  n as (select count(*)::float8 as n from peers),
  items as (
    select i.checkin_id, i.restaurant_id, i.visits, r.area, r.cuisine
    from food_checkin_items i join peers p on p.id = i.checkin_id
    left join food_restaurants r on r.id = i.restaurant_id
  ),
  popularity as (select restaurant_id, count(*) as people from items group by restaurant_id),
  per as (
    select p.id,
      coalesce(count(i.restaurant_id), 0) as tried,
      coalesce(sum(i.visits), 0) as visits,
      count(distinct i.cuisine) as cuisines,
      count(distinct i.area) as areas,
      coalesce(max(i.visits), 0) as loyalty,
      coalesce(avg(1 - pop.people / (select n from n)), 0) as niche
    from peers p
    left join items i on i.checkin_id = p.id
    left join popularity pop on pop.restaurant_id = i.restaurant_id
    group by p.id
  ),
  mine as (select * from per where id = p_id),
  ranked as (
    select i.restaurant_id, i.checkin_id,
           rank() over (partition by i.restaurant_id order by i.visits desc) as place,
           count(*) over (partition by i.restaurant_id) as people
    from items i
  )
  select case when not exists (select 1 from me) then null else json_build_object(
    'n', (select count(*) from peers),
    'below', (select count(*) from per where tried < (select tried from mine)),
    'ties', (select count(*) from per where tried = (select tried from mine)),
    'median', (select percentile_cont(0.5) within group (order by tried) from per),
    'hist', (select json_agg(coalesce(c, 0) order by b)
             from generate_series(0, 9) b
             left join (select least(tried / 10, 9) as bucket, count(*) as c from per group by 1) h on h.bucket = b),
    'popularity', (select coalesce(json_object_agg(restaurant_id, people), '{}'::json) from popularity),
    'metrics', json_build_object(
      'visits', json_build_object('mine', (select visits from mine),
        'below', (select count(*) from per where visits < (select visits from mine)),
        'ties', (select count(*) from per where visits = (select visits from mine))),
      'cuisines', json_build_object('mine', (select cuisines from mine),
        'below', (select count(*) from per where cuisines < (select cuisines from mine)),
        'ties', (select count(*) from per where cuisines = (select cuisines from mine))),
      'areas', json_build_object('mine', (select areas from mine),
        'below', (select count(*) from per where areas < (select areas from mine)),
        'ties', (select count(*) from per where areas = (select areas from mine))),
      'loyalty', json_build_object('mine', (select loyalty from mine),
        'below', (select count(*) from per where loyalty < (select loyalty from mine)),
        'ties', (select count(*) from per where loyalty = (select loyalty from mine))),
      'niche', json_build_object('mine', (select round(niche::numeric, 4) from mine),
        'below', (select count(*) from per where round(niche::numeric, 4) < (select round(niche::numeric, 4) from mine)),
        'ties', (select count(*) from per where round(niche::numeric, 4) = (select round(niche::numeric, 4) from mine)))
    ),
    'fans', (select coalesce(json_agg(json_build_object('id', restaurant_id, 'place', place, 'people', people)
                                      order by place, people desc), '[]'::json)
             from ranked where checkin_id = p_id and place <= 3 and people >= 2)
  ) end;
$$;

revoke all on function public.food_stats from public, anon, authenticated;
